import type { Metadata } from "next";
import { getDb } from "@projectos/db";
import { listNotifications } from "@projectos/notifications";
import { PageHeader } from "@projectos/ui";
import { requireContext } from "@/lib/session";
import { NotificationList } from "@/components/notifications/NotificationList";

export const metadata: Metadata = { title: "Notifications" };

export default async function NotificationsPage() {
  const ctx = await requireContext();
  const { items, unread } = await listNotifications(getDb(), ctx);
  return (
    <div>
      <PageHeader
        title="Notifications"
        description="In-app only (no email or SMS in this phase). Generated by the worker from the Postgres outbox; each reminder is delivered once per due date."
      />
      <NotificationList unread={unread} items={items.map((n) => ({ ...n, readAt: n.readAt?.toISOString() ?? null, createdAt: n.createdAt.toISOString() }))} />
    </div>
  );
}
